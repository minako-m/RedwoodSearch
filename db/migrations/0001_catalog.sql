-- Course catalog: quarters, department listings, sections, meeting times, instructors.

CREATE TABLE terms (
    id            integer PRIMARY KEY,          -- ExploreCourses termId, e.g. 1272
    name          text NOT NULL UNIQUE,         -- "2026-2027 Autumn"
    academic_year text NOT NULL,                -- "2026-2027"
    quarter       text NOT NULL CHECK (quarter IN ('Autumn', 'Winter', 'Spring', 'Summer'))
);

-- One row per department listing. Cross-listed listings (CS 152 = COMM 122) share course_id.
CREATE TABLE course_listings (
    id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject          text NOT NULL,
    code             text NOT NULL,
    course_id        integer NOT NULL,          -- ExploreCourses courseId; groups cross-listings
    academic_year    text NOT NULL,
    title            text NOT NULL,             -- cross-listing suffix "(CS 152, ...)" removed
    description      text NOT NULL DEFAULT '',
    description_hash text NOT NULL,             -- derived fields below are recomputed only when this changes
    units_min        smallint NOT NULL CHECK (units_min >= 0),
    units_max        smallint NOT NULL CHECK (units_max >= units_min),
    gers             text[] NOT NULL DEFAULT '{}',   -- normalized, e.g. {WAY-FR, GER:DB-NatSci}
    grading          text,
    career           text,                      -- UG, GR, MED, LAW, GSB
    final_exam       text,                      -- Y, N, L
    remote           boolean,
    repeatable       boolean,

    -- Prerequisites, extracted from the description. Only hard requirements count as prerequisites:
    -- 'recommended' courses are treated as having none.
    prereq_status    text NOT NULL CHECK (prereq_status IN ('none', 'recommended', 'consent', 'required')),
    prereq_text      text,                      -- the sentence the status came from, for traceability
    prereq_courses   text[] NOT NULL DEFAULT '{}',   -- course codes mentioned, e.g. {CS 106B}
    prereq_source    text NOT NULL CHECK (prereq_source IN ('rules', 'llm')),

    search           tsvector GENERATED ALWAYS AS (
                         setweight(to_tsvector('english', title), 'A') ||
                         setweight(to_tsvector('english', description), 'B')
                     ) STORED,

    UNIQUE (subject, code, academic_year)
);
CREATE INDEX course_listings_course_id ON course_listings (course_id);
CREATE INDEX course_listings_gers ON course_listings USING gin (gers);
CREATE INDEX course_listings_search ON course_listings USING gin (search);

CREATE TABLE sections (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id      integer NOT NULL REFERENCES course_listings (id) ON DELETE CASCADE,
    term_id         integer NOT NULL REFERENCES terms (id),
    class_id        integer NOT NULL,           -- ExploreCourses classId, unique within a term
    section_number  text NOT NULL,
    component       text NOT NULL,              -- LEC, DIS, SEM, LAB, INS, ...
    units_min       smallint NOT NULL CHECK (units_min >= 0),
    units_max       smallint NOT NULL CHECK (units_max >= units_min),
    -- scheduled: has real meeting times. arranged: independent study / thesis / clerkship, never
    -- has a time. tba: a regular class whose time isn't published yet.
    timing          text NOT NULL CHECK (timing IN ('scheduled', 'arranged', 'tba')),
    instruction_mode text,
    enroll_status   text,
    num_enrolled    integer,
    max_enrolled    integer,
    num_waitlist    integer,
    max_waitlist    integer,
    notes           text,
    UNIQUE (term_id, class_id)
);
CREATE INDEX sections_listing_id ON sections (listing_id);

CREATE TABLE meetings (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    section_id   integer NOT NULL REFERENCES sections (id) ON DELETE CASCADE,
    days         smallint NOT NULL DEFAULT 0 CHECK (days BETWEEN 0 AND 127),  -- bit 0 = Monday ... bit 6 = Sunday
    start_minute smallint CHECK (start_minute BETWEEN 0 AND 1439),           -- minutes since midnight
    end_minute   smallint CHECK (end_minute BETWEEN 1 AND 1440),
    start_date   date,
    end_date     date,
    location     text,
    CHECK ((start_minute IS NULL) = (end_minute IS NULL)),
    CHECK (start_minute < end_minute),
    CHECK (start_date <= end_date)
);
CREATE INDEX meetings_section_id ON meetings (section_id);

CREATE TABLE instructors (
    sunet      text PRIMARY KEY,
    name       text NOT NULL,                   -- "Hancock, J."
    first_name text,
    last_name  text
);

CREATE TABLE meeting_instructors (
    meeting_id integer NOT NULL REFERENCES meetings (id) ON DELETE CASCADE,
    sunet      text NOT NULL REFERENCES instructors (sunet),
    role       text,                            -- PI, TA, SI, GP
    PRIMARY KEY (meeting_id, sunet)
);
